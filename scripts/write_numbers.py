    w("|---|---|---|")
    w(
        f"| Recall (failing satellites warned before failure) | **{pct(o['recall'])}** ({round(o['recall'] * o['failing'])} / {o['failing']}) | {pct(lo)}–{pct(hi)} (Wilson) |"
    )
    w(
        f"| Median warning lead time | **{o['median_lead_s']:.0f} s** (IQR {o['iqr_lead_s'][0]:.0f}–{o['iqr_lead_s'][1]:.0f} s) | {o['median_lead_ci'][0]:.0f}–{o['median_lead_ci'][1]:.0f} s (bootstrap) |"
    )
    w(
        f"| False-positive rate, measured on benign steps (target 0.1 % on validation) | {o['realized_fpr'] * 100:.3f} % | — |"
    )
    w(f"| Pre-onset false alarms | {o['pre_onset_false_alarms_per_sat_hour']:.2f} per satellite-hour | — |")
    w(f"| AUROC | {o['auroc']:.3f} | — |")
    w("")
    w(
        'Say: *"On held-out out-of-distribution scenarios, at a 0.1 % false-positive rate, the forecaster warned '
        f"of every one of {o['failing']} failures, with a median lead of {o['median_lead_s']:.0f} s (simulation).\"* "
        "Lead time is measured from the first alert at or after the attack's onset; an alert before onset is "
        "counted as a false alarm and earns no lead."
    )
    w("")

    # ------------------------------------------------------------------ ID table with caveat
    w("## In-distribution and real-noise test sets, and baselines")
    w("")
    w(
        "Source: `results/eval/metrics.json`, same command. **Saturation caveat:** on these synthetic sets every "
        "ablation (single model, no engineered features, unconstrained, no residual) also reaches recall 1.00, "
        "so the benefit of the graph structure is not demonstrated by these numbers."
    )
    w("")
    w(
        "| Method | ID recall | ID median lead | OOD recall | OOD median lead | Real-noise recall | Real-noise median lead | Pre-onset false alarms / sat-h (ID) |"
    )
    w("|---|---|---|---|---|---|---|---|")
    names = {
        "ensemble": "Ensemble (5 seeds), alert at 0.1 % FPR",
        "ensemble@act": "Ensemble at the core's action threshold",
        "single": "Single model (ablation)",
        "no_eng": "No engineered features (ablation)",
        "threshold": "Static threshold (baseline)",
        "trajectory": "Trajectory extrapolation (baseline)",
        "lstm_ae": "LSTM autoencoder (baseline)",
        "gdn": "GDN (baseline)",
    }
    for k, label in names.items():
        row = [label]
        for sp in ("test_id", "test_ood", "test_real"):
            r = met["splits"][sp]["methods"].get(k)
            row += ["—", "—"] if r is None else [f"{r['recall']:.2f}", f"{r['median_lead_s']:.0f} s"]
        rid = met["splits"]["test_id"]["methods"].get(k, {})
        row.append(f"{rid.get('pre_onset_false_alarms_per_sat_hour', float('nan')):.2f}")
        w("| " + " | ".join(row) + " |")
    w("")
    ece = {sp: max(met["splits"][sp]["calibration"].values()) for sp in ("test_id", "test_ood", "test_real")}
    w(
        f"Calibration: expected calibration error ≤ {max(ece.values()):.3f} at every horizon on all three sets "
        "(`calibration` in the same file). Next-subsystem top-1: "
        f"ID {met['splits']['test_id']['next_sub']['top1']:.2f}, OOD {met['splits']['test_ood']['next_sub']['top1']:.2f}, "
        f"Real {met['splits']['test_real']['next_sub']['top1']:.2f}. Malicious-vs-fault AUROC: "
        f"ID {met['splits']['test_id']['malicious']['auroc']:.2f}, OOD {met['splits']['test_ood']['malicious']['auroc']:.2f}."
    )
    w("")
    w(
        f"Stress (`results/eval/stress.json`, `python -m eval.stress`): recall {stress['original']['recall']:.2f} original, "
        f"{stress['spoof_ground']['recall']:.2f} with spoofed ground origins, {stress['no_commands']['recall']:.2f} with no "
        "commands at all: the cyber features are not what detects (saturation again)."
    )
